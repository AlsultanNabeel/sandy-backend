#pragma once
#include "esp_err.h"
#include <stdbool.h>

esp_err_t wifi_sandy_start(void);
bool      wifi_sandy_is_connected(void);

// آخر عنوان أخذه اللوح، أو نص فاضي لو لسا ما أخذ. بينحط بالنبضة عشان يظهر
// بالتطبيق: العنوان بيتغيّر كل ما الراوتر يعيد التوزيع، وبلا ما اللوح يقوله،
// إيجاده بيصير مسح شبكة وتخمين.
const char *wifi_sandy_ip(void);

// ── تغيير الشبكة من التطبيق ──────────────────────────────────────────────────
//
// **المشكلة اللي هالتصميم موجود عشانها:** لو غيّرنا الشبكة وكلمة السر غلط، اللوح
// بيفقد النت — يعني بيفقد الطريقة الوحيدة اللي فيها بنقدر نقوله «رجاع». وساعتها
// ما إله حلّ غير كبل وحرق. تغيير شبكة بدون رجوع تلقائي ميزة بتخرب الجهاز مرّة من
// كل عشرة.
//
// فالخطوات: بنجرّب الجديدة، وإذا ما نجحت خلال `WIFI_TRY_WINDOW_MS`، بنرجّع
// القديمة لحالنا. القديمة ما بتنمسح إلا بعد ما الجديدة تشتغل فعلًا.
//
// وفي حارس إقلاع كمان: بيانات «قيد التجربة» بتنمسح أول ما اللوح يشتغل. يعني حتى
// لو انقطعت الكهربا بنص التجربة، بيرجع اشتغل ع الشبكة اللي كان عليها.

#define WIFI_TRY_WINDOW_MS 25000

typedef enum {
    WIFI_SWITCH_OK = 0,        // الجديدة اشتغلت وانحفظت
    WIFI_SWITCH_FAILED,        // ما اتصلت — رجعنا للقديمة
    WIFI_SWITCH_BUSY,          // في تجربة شغّالة
    WIFI_SWITCH_BAD_ARGS,
} wifi_switch_result_t;

// جرّب شبكة جديدة. بتحجز لحدّ ما تخلص التجربة (٢٥ ثانية كحدّ أقصى).
//
// بتنستدعى من معالج MQTT، وهو ع مهمّة إلها مخزنها — مش من ISR ولا من مهمّة
// الصوت.
wifi_switch_result_t wifi_sandy_switch(const char *ssid, const char *pass);

// اسم الشبكة اللي اللوح عليها الآن — بيروح بالنبضة عشان التطبيق يوريك
// شو الوضع قبل ما تغيّر.
const char *wifi_sandy_ssid(void);
