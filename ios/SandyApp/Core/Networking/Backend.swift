import Foundation

/// وين بيقع الخادم، وكيف بينحفظ الاختيار.
///
/// كان العنوان مكتوب حرفيًا بمكانين — `AppState` والنوايا (Siri). وهاد النوع من
/// التكرار ما بينكسر وقت ما تكتبه، بينكسر بعد شهور: بتغيّر واحد وبتنسى التاني،
/// فالتطبيق بيكلّم الخادم الجديد والاختصارات بتضل ع القديم، والعرَض إنه ميزة
/// بتشتغل من التطبيق وما بتشتغل من سيري. تشخيصه بياخد ساعات.
///
/// مصدر واحد، وكل حدا بيقرا منه.
enum Backend {
    /// المفتاح بالتفضيلات — مشترك بين التطبيق وإضافاته، فلازم يضل نفسه.
    static let urlDefaultsKey = "sandy_base_url"

    /// العنوان الافتراضي. الاسم موروث من المشروع القديم؛ اللي منشور عليه هو
    /// الخادم الحالي (شوف docs/REPOS_AND_DEPLOY.md).
    static let defaultURL = "https://sandy-robot-3da0693d32f7.herokuapp.com"

    /// العنوان المستعمل فعليًا: المحفوظ إن وُجد، وإلا الافتراضي.
    /// بيرجّع الافتراضي كمان لو المحفوظ فاضي — قيمة فاضية بالتفضيلات بتعطي
    /// طلبات بلا مضيف، وخطأها بيبيّن كأنه انقطاع شبكة.
    static var currentURL: String {
        let saved = UserDefaults.standard.string(forKey: urlDefaultsKey) ?? ""
        return saved.isEmpty ? defaultURL : saved
    }
}
